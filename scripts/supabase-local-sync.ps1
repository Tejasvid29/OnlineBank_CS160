<#
.SYNOPSIS
  Builds the LOCAL Supabase stack so it matches the remote project's structure (no data).

.DESCRIPTION
  The structure (tables, constraints, indexes, RLS + policies, functions, grants, ensure_rls event
  trigger, pg_cron jobs, the check-deposits bucket) lives in
  supabase/migrations/20261116000000_remote_baseline.sql, which was captured read-only from the
  remote project. It needs no remote access and no user data, so it is committed to git.

  This script:
    1. starts the local stack (supabase start; applies the migration on a fresh DB)
    2. with -Reset, rebuilds the local DB from the migration (supabase db reset)
    3. writes backend/.env.local so the FastAPI backend talks to the local stack

  Requires Docker Desktop running and Node (uses `npx supabase`).

.EXAMPLE
  .\scripts\supabase-local-sync.ps1          # start + point backend at local
  .\scripts\supabase-local-sync.ps1 -Reset   # wipe local DB, re-apply migrations, re-seed
  .\scripts\supabase-local-sync.ps1 -Seed    # load mock data into the running local DB
#>
[CmdletBinding()]
param([switch]$Reset, [switch]$Seed)
$ErrorActionPreference = 'Stop'
Set-Location (Split-Path $PSScriptRoot -Parent)

function Say($m) { Write-Host "==> $m" -ForegroundColor Cyan }
# npx.cmd, not `npx`: on Windows `npx` resolves to npx.ps1, which drops the arguments and just prints the CLI help.
function Sb { & npx.cmd --yes supabase@latest @args; if ($LASTEXITCODE) { throw "supabase $($args -join ' ') failed" } }
function SbOut { $o = & npx.cmd --yes supabase@latest @args; if ($LASTEXITCODE) { throw "supabase $($args -join ' ') failed" }; ($o | Out-String) }

docker info *> $null
if ($LASTEXITCODE) { throw "Docker isn't running. Start Docker Desktop and retry." }

Say 'Starting local Supabase stack (applies supabase/migrations on first start)'
Sb start

if ($Reset) {
  Say 'Rebuilding local DB from migrations'
  Sb db reset --local
}

# supabase/seed.sql (mock users, accounts, transactions) runs automatically on first start and on -Reset.
# -Seed loads it into an already-running local DB. It skips itself if admin@gmail.com already exists.
if ($Seed) {
  Say 'Loading supabase/seed.sql into the local DB'
  $projectId = (Select-String -Path 'supabase/config.toml' -Pattern '^project_id\s*=\s*"(.+)"').Matches[0].Groups[1].Value
  cmd /c "docker exec -i supabase_db_$projectId psql -U postgres -d postgres -v ON_ERROR_STOP=1 -q < supabase\seed.sql"
  if ($LASTEXITCODE) { throw 'seed.sql failed' }
}

Say 'Writing backend/.env.local (overrides backend/.env; delete it to go back to the remote project)'
$s = SbOut status -o env
function V($k) { [regex]::Match($s, "(?m)^$k=`"?([^`"\r\n]+)").Groups[1].Value }
$api = V 'API_URL'
if (-not $api) { throw "Could not read API_URL from 'supabase status -o env' (is the stack running?). Not writing backend/.env.local." }
$pub = if (V 'PUBLISHABLE_KEY') { V 'PUBLISHABLE_KEY' } else { V 'ANON_KEY' }
$sec = if (V 'SECRET_KEY') { V 'SECRET_KEY' } else { V 'SERVICE_ROLE_KEY' }
@"
# Generated by scripts/supabase-local-sync.ps1: points the backend at the LOCAL Supabase stack.
SUPABASE_URL=$api
SUPABASE_PUBLISHABLE_KEY=$pub
SUPABASE_SECRET_KEY=$sec
SUPABASE_JWKS_URL=$api/auth/v1/.well-known/jwks.json
"@ | Set-Content 'backend/.env.local' -Encoding utf8

Write-Host "Studio: $(V 'STUDIO_URL')   Local emails (Mailpit): $(V 'INBUCKET_URL')"
Say 'Done. Manager login: admin@gmail.com / 12345678. Customers (alice|bob|carol|dave)@example.com / password123.'
